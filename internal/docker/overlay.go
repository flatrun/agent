const overlayHeader = "# Generated by FlatRun from the service settings in service.yml.\n" +
	"# Change them in FlatRun; edits made here are replaced on the next save.\n"

type overlayFile struct {
	Services map[string]overlayService `yaml:"services"`
}

type overlayService struct {
	Deploy      *overlayDeploy    `yaml:"deploy,omitempty"`
	Restart     string            `yaml:"restart,omitempty"`
	Logging     *overlayLogging   `yaml:"logging,omitempty"`
	Environment map[string]string `yaml:"environment,omitempty"`
	Command     []string          `yaml:"command,omitempty"`
	Entrypoint  []string          `yaml:"entrypoint,omitempty"`
}

type overlayDeploy struct {
	Resources struct {
		Limits map[string]string `yaml:"limits"`
	} `yaml:"resources"`
}

type overlayLogging struct {
	Driver  string            `yaml:"driver"`
	Options map[string]string `yaml:"options"`
}

// OverlayValidationError carries compose's own explanation of why the
// merged configuration was refused.
type OverlayValidationError struct {
	Output string
}

func (e *OverlayValidationError) Error() string {
	return "compose rejected the service settings: " + e.Output
}

// RenderOverlay returns the overlay compose file for the given settings, or
// nil when no service sets anything.
func RenderOverlay(settings map[string]models.ServiceSettings) ([]byte, error) {
	file := overlayFile{Services: map[string]overlayService{}}
	names := make([]string, 0, len(settings))
	for name := range settings {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		s := settings[name]
		if s.IsEmpty() {
			continue
		}
		svc := overlayService{Restart: s.Restart}
		if r := s.Resources; r != nil && (r.CPUs != "" || r.Memory != "") {
			svc.Deploy = &overlayDeploy{}
			svc.Deploy.Resources.Limits = map[string]string{}
			if r.CPUs != "" {
				svc.Deploy.Resources.Limits["cpus"] = r.CPUs
			}
			if r.Memory != "" {
				svc.Deploy.Resources.Limits["memory"] = strings.ToLower(r.Memory)
			}
		}
		if l := s.Logging; l != nil && l.MaxSize != "" {
			svc.Logging = &overlayLogging{Driver: "json-file", Options: map[string]string{"max-size": strings.ToLower(l.MaxSize)}}
			if l.MaxFiles > 0 {
				svc.Logging.Options["max-file"] = strconv.Itoa(l.MaxFiles)
			}
		}
		if len(s.Environment) > 0 {
			svc.Environment = map[string]string{}
			for k, v := range s.Environment {
				svc.Environment[k] = escapeInterpolation(v)
			}
		}
		svc.Command = escapeAll(s.Command)
		svc.Entrypoint = escapeAll(s.Entrypoint)
		file.Services[name] = svc
	}
	if len(file.Services) == 0 {
		return nil, nil
	}
	var buf bytes.Buffer
	buf.WriteString(overlayHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(file); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Compose interpolates ${VAR} in every value of every compose file; the
// settings hold literal values, so $ is doubled to reach the container as-is.
func escapeInterpolation(value string) string {
	return strings.ReplaceAll(value, "$", "$$")
}

func escapeAll(values []string) []string {
	if len(values) == 0 {
		return nil
	}
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = escapeInterpolation(v)
	}
	return out
}

func overlayPath(deploymentPath string) string {
	return filepath.Join(deploymentPath, models.ComposeOverlayFile)
}

// validateOverlay runs `compose config` over the deployment's compose file
// and the candidate overlay, which catches unknown services and values
// compose cannot parse before the overlay is installed.
func (c *ComposeExecutor) validateOverlay(deploymentPath, candidate string) error {
	composeCmd := c.findComposeCommand()
	if composeCmd == "" {
		return fmt.Errorf("docker compose command not found")
	}
	base := c.findComposeFile(deploymentPath)
	if base == "" {
		return fmt.Errorf("no compose file found in %s", deploymentPath)
	}
	args := []string{"-f", base, "-f", candidate, "-p", c.getProjectName(deploymentPath)}
	if _, err := os.Stat(filepath.Join(deploymentPath, ".env.flatrun")); err == nil {
		args = append(args, "--env-file", ".env.flatrun")
	}
	args = append(args, "config", "-q")
	if composeCmd != "docker-compose" {
		args = append([]string{"compose"}, args...)
		composeCmd = "docker"
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, composeCmd, args...)
	cmd.Dir = deploymentPath
	if out, err := cmd.CombinedOutput(); err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return &OverlayValidationError{Output: msg}
	}
	return nil
}

// SetOverlayValidator replaces the compose check run before an overlay is
// installed; tests use it where no compose binary is available.
func (m *Manager) SetOverlayValidator(fn func(deploymentPath, candidate string) error) {
	m.overlayValidator = fn
}

// ComposeOverlay returns the deployment's current overlay, empty when it
// has none.
func (m *Manager) ComposeOverlay(name string) (string, error) {
	m.mu.RLock()
	deployment, err := m.discovery.GetDeployment(name)
	m.mu.RUnlock()
	if err != nil {
		return "", err
	}
	data, err := os.ReadFile(overlayPath(deployment.Path))
	if os.IsNotExist(err) {
		return "", nil
	}
	return string(data), err
}

// ApplyServiceSettings renders the overlay for settings, checks it with
// compose and installs it. A rejected overlay leaves the installed one in
// place. The replaced overlay is kept next to it with a .bak suffix.
func (m *Manager) ApplyServiceSettings(name string, settings map[string]models.ServiceSettings) error {
	m.overlayMu.Lock()
	defer m.overlayMu.Unlock()

	m.mu.RLock()
	deployment, err := m.discovery.GetDeployment(name)
	m.mu.RUnlock()
	if err != nil {
		return err
	}
	path := overlayPath(deployment.Path)
	content, err := RenderOverlay(settings)
	if err != nil {
		return err
	}
	current, readErr := os.ReadFile(path)
	exists := readErr == nil
	if exists && bytes.Equal(current, content) {
		return nil
	}
	if content == nil {
		if !exists {
			return nil
		}
		return os.Rename(path, path+".bak")
	}

	candidate := path + ".new"
	if err := os.WriteFile(candidate, content, 0644); err != nil {
		return err
	}
	defer os.Remove(candidate)

	validate := m.overlayValidator
	if validate == nil {
		validate = m.executor.validateOverlay
	}
	if err := validate(deployment.Path, candidate); err != nil {
		return err
	}
	if exists {
		if err := os.WriteFile(path+".bak", current, 0644); err != nil {
			return err
		}
	}
	return os.Rename(candidate, path)
}
